def create_app() -> FastAPI:
    app = FastAPI(
        title="Squire",
        version=__version__,
        description="Autonomous SOC analyst -- Phase 17 FastAPI surface.",
    )

    # Keycloak token connectivity check (Phase 20 / JIT-CA Gate 2 scaffold).
    # When kc_enabled=True, fetch a service-account token at startup so the
    # process fails fast on misconfiguration instead of failing on first tool
    # call. When kc_enabled=False, skip silently.
    if settings.kc_enabled:
        from .keycloak_client import KeycloakAuthError, get_kc_client
        try:
            get_kc_client().get_token()
            log.info("kc.startup.ok client_id=%s realm=%s",
                     settings.kc_client_id, settings.kc_realm)
        except KeycloakAuthError as exc:
            log.error("kc.startup.failed reason=%s", exc)
            raise

    @app.get("/health")
    def health() -> dict[str, str]:
        return {"status": "ok", "service": "squire", "version": __version__}

    @app.get("/healthz")
    def healthz() -> dict[str, str]:
        return {"status": "ok"}

    @app.post("/alert")
    def alert_endpoint(  # noqa: C901 -- high-level orchestrator, intentionally linear
        req: AlertRequest,
        request: Request,
        response: Response,
        x_squire_token: str | None = Header(default=None, alias="X-Squire-Token"),
        x_internal: str | None = Header(default=None, alias="X-Internal"),
        x_squire_max_iters: str | None = Header(
            default=None, alias="X-Squire-Max-Iterations"
        ),
    ):
        _auth(x_squire_token, x_internal, request)
        alert_id = req.alert_id or f"sq-{uuid.uuid4()}"

        # ---------------- Dedup (criterion #18) ----------------
        dedup = check_and_register(req.alert, alert_id=alert_id, trace_id=None)
        if dedup.is_duplicate:
            response.headers["X-Squire-Deduplicated"] = "true"
            return AlertResponse(
                alert_id=alert_id,
                severity="DEDUPLICATED",
                report={
                    "info": "duplicate within dedup window",
                    "original_alert_id": dedup.original_alert_id,
                },
                citations={},
                trace_id=dedup.original_trace_id,
                trace_url=(
                    f"{settings.langfuse_host}/trace/{dedup.original_trace_id}"
                    if dedup.original_trace_id
                    else None
                ),
                duration_ms=0,
                cost_usd=0.0,
                deduplicated=True,
                original_alert_id=dedup.original_alert_id,
                original_trace_id=dedup.original_trace_id,
            )

        # ---------------- Pre-graph PII scan (17-10 remediation) ----------------
        # NeMo's input rail only fronts draft + critique nodes. PII in the raw
        # alert payload can be summarised away by classify/retrieve/enrich
        # before the rail ever sees it. Red-team cases 03-04 demonstrated this
        # gap. Scanning the raw payload here closes it at sub-millisecond cost.
        pii_hit = pii_scan(req.alert)
        if pii_hit is not None:
            response.headers["X-Squire-Rail-Blocked"] = "true"
            return AlertResponse(
                alert_id=alert_id,
                severity="BLOCKED",
                report=build_block_response(
                    reason_code="PII_DETECTED_PRE_GRAPH",
                    rail_name="pre_graph",
                    rule_name=f"regex_{pii_hit.entity.lower()}",
                    input_snippet=pii_snippet(req.alert, pii_hit),
                    extra={"blocked_by": "pre_graph_pii"},
                ),
                citations={},
                trace_id=None,
                trace_url=None,
                duration_ms=0,
                cost_usd=0.0,
            )

        # ---------------- Cost ceiling (criterion #15) ----------------
        budget = consult_budget()
        if budget.breach and budget.mode == "refuse":
            return JSONResponse(
                status_code=503,
                content={
                    "error": "service_unavailable",
                    "reason_code": "daily_cost_ceiling_reached",
                    "details": {
                        "spent_today_usd": budget.spent,
                        "ceiling_usd": budget.ceiling,
                        "breach_mode": budget.mode,
                    },
                    "retry_after_seconds": 3600,
                },
                headers={"Retry-After": "3600"},
            )

        backend_override = budget.backend_override
        degraded_reason_from_budget = budget.reason if backend_override else None

        # ---------------- Graph invocation ----------------
        override_iters = _parse_max_iters(x_squire_max_iters)

        t0 = time.monotonic()
        prev_backend = os.environ.get("SQUIRE_LLM_BACKEND")
        try:
            if backend_override:
                os.environ["SQUIRE_LLM_BACKEND"] = backend_override
            state = _invoke_graph(req.alert, alert_id, override_iters)
        finally:
            if prev_backend is not None:
                os.environ["SQUIRE_LLM_BACKEND"] = prev_backend
            elif backend_override:
                os.environ.pop("SQUIRE_LLM_BACKEND", None)
        duration_ms = int((time.monotonic() - t0) * 1000)

        # ---------------- Persistence ----------------
        try:
            save_investigation(
                alert_id,
                state,
                duration_ms,
                alert_payload=req.alert,
                source=req.source or "webhook",
            )
            if state.get("trace_id"):
                dedup_update_trace(dedup.sig, state["trace_id"])
        except Exception as e:  # pragma: no cover
            log.warning("persist failed for %s: %s", alert_id, e)
            state.setdefault("errors", []).append(f"persist_failed: {e}")

        # ---------------- Degraded-mode header ----------------
        degraded = bool(state.get("_degraded_mode", False)) or bool(backend_override)
        if degraded:
            response.headers["X-Squire-Degraded-Mode"] = "true"

        # ---------------- Rail-block header (criterion #25) ----------------
        if _extract_nemo_block(state) is not None:
            response.headers["X-Squire-Rail-Blocked"] = "true"

        return _build_response(
            alert_id=alert_id,
            state=state,
            duration_ms=duration_ms,
            degraded_override_reason=degraded_reason_from_budget,
        )

    @app.post("/replay/{alert_id}")
    def replay_endpoint(
        alert_id: str,
        request: Request,
        response: Response,
        x_squire_token: str | None = Header(default=None, alias="X-Squire-Token"),
        x_internal: str | None = Header(default=None, alias="X-Internal"),
        x_squire_max_iters: str | None = Header(
            default=None, alias="X-Squire-Max-Iterations"
        ),
    ):
        _auth(x_squire_token, x_internal, request)
        stored = load_alert(alert_id)
        if stored is None:
            raise HTTPException(status_code=404, detail="alert_id not found")

        new_id = f"{alert_id}-replay-{uuid.uuid4().hex[:8]}"
        override_iters = _parse_max_iters(x_squire_max_iters)

        t0 = time.monotonic()
        state = _invoke_graph(stored, new_id, override_iters)
        duration_ms = int((time.monotonic() - t0) * 1000)

        try:
            save_investigation(
                new_id, state, duration_ms, alert_payload=stored, source="replay"
            )
        except Exception as e:  # pragma: no cover
            log.warning("replay persist failed for %s: %s", new_id, e)

        if state.get("_degraded_mode"):
            response.headers["X-Squire-Degraded-Mode"] = "true"

        return _build_response(alert_id=new_id, state=state, duration_ms=duration_ms)

    return app


app = create_app()
