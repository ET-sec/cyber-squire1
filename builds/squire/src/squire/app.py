"""Squire FastAPI surface (17-09).

Endpoints:
  GET  /health          -- always 200 JSON; no auth.
  GET  /healthz         -- legacy alias for /health.
  POST /alert           -- run the graph on an incoming alert. Dual auth.
  POST /replay/{id}     -- re-run the graph on a stored alert payload.

Cross-cutting concerns wired here:
  - Auth middleware (X-Squire-Token + optional X-Internal for net-core internal path)
  - Alert dedup (criterion #18)
  - Daily cost ceiling with breach dispatch (criterion #15)
  - X-Squire-Max-Iterations header override -> graph (17-12 eval harness)
  - Citation guard middleware at boundary (criterion #17 defense-in-depth)
  - Actions allow-list enforcement (criterion #16) in recommend-only mode
  - Degraded-mode response header + footer (criterion #19)
  - Structured block-reason JSON on breach (criterion #25 scaffold)
"""
from __future__ import annotations

import json as _json
import logging
import os
import time
import uuid
from typing import Any

from fastapi import FastAPI, Header, HTTPException, Request, Response
from fastapi.responses import JSONResponse

from . import __version__
from .actions_allowlist import RecommendOnlyViolation, enforce_response as allowlist_enforce
from .api_models import AlertRequest, AlertResponse
from .citations import filter_citations
from .cost_ceiling import consult as consult_budget
from .dedup import check_and_register, update_trace_id as dedup_update_trace
from .persist import load_alert, save_investigation
from .pre_graph_pii import build_snippet as pii_snippet, scan as pii_scan
from .response_builder import build_block_response
from .settings import settings

log = logging.getLogger("squire.app")

DEGRADED_FOOTER = (
    "Degraded mode: primary LLM unreachable, response generated by local model."
)


