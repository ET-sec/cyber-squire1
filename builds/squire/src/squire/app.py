def _invoke_graph(
    alert: dict[str, Any], alert_id: str, max_iters_override: int | None
) -> dict[str, Any]:
    """Lazy-import the graph so test harnesses with graph monkeypatched work."""
    from .graph import invoke_with_trace  # noqa: WPS433 (runtime import by design)

    return invoke_with_trace(
        alert, alert_id=alert_id, max_iterations_override=max_iters_override
    )


def _auth(
    token_header: str | None,
    internal_header: str | None,
    request: Request,
) -> str:
    """Raise 401 unless the bearer matches.

    When X-Internal=1 AND the client IP is in the docker bridge range, the path
    is tagged as "internal" so downstream logging can differentiate. The secret
    must still be correct in both cases -- the internal flag does NOT bypass
    the token check.
    """
    expected = settings.squire_webhook_token.get_secret_value()
    if not token_header or token_header != expected:
        raise HTTPException(status_code=401, detail="unauthorized")
    if internal_header == "1":
        client_host = request.client.host if request.client else ""
        if (
            client_host.startswith("172.")
            or client_host.startswith("127.")
            or client_host == "::1"
        ):
            return "internal"
    return "external"


def _parse_max_iters(header_val: str | None) -> int | None:
    """Parse X-Squire-Max-Iterations as an int in [0, 10]; None on failure."""
    if not header_val:
        return None
    try:
        v = int(header_val)
    except Exception:
        return None
    if 0 <= v <= 10:
        return v
    return None


def _extract_nemo_block(state: dict[str, Any]) -> dict[str, str] | None:
    """Return parsed nemo_block fields from state.errors, or None.

    Looks for ``nemo_block:reason_code=X;rail_name=Y;rule_name=Z;snippet=W``
    markers stamped by draft/critique nodes when NeMo Guardrails fires.
    """
    errors = state.get("errors") or []
    for err in errors:
        if not isinstance(err, str) or not err.startswith("nemo_block:"):
            continue
        body = err[len("nemo_block:"):]
        fields: dict[str, str] = {}
        for pair in body.split(";"):
            if "=" in pair:
                k, v = pair.split("=", 1)
                fields[k.strip()] = v
        return {
            "reason_code": fields.get("reason_code", "RAIL_BLOCK"),
            "rail_name": fields.get("rail_name", "default"),
            "rule_name": fields.get("rule_name", "unknown"),
            "input_snippet": fields.get("snippet", ""),
        }
    return None


def _build_response(
    *,
    alert_id: str,
    state: dict[str, Any],
    duration_ms: int,
    degraded_override_reason: str | None = None,
) -> AlertResponse:
    """Assemble the outward AlertResponse from a graph final-state dict.

    Runs the citation-guard + allow-list rewrite at the FastAPI boundary as
    defense-in-depth beyond the draft node's own validators. If a NeMo rail
    fired during the graph, returns a structured block response (criterion
    #25) and short-circuits the normal report assembly.
    """
    # Rail-block short-circuit (criterion #25)
    block = _extract_nemo_block(state)
    if block is not None:
        return AlertResponse(
            alert_id=alert_id,
            severity="BLOCKED",
            report=build_block_response(
                reason_code=block["reason_code"],
                rail_name=block["rail_name"],
                rule_name=block["rule_name"],
                input_snippet=block["input_snippet"],
                extra={"blocked_by": "nemo_guardrails"},
            ),
            citations={},
            trace_id=state.get("trace_id"),
            trace_url=(
                f"{settings.langfuse_host}/trace/{state.get('trace_id')}"
                if state.get("trace_id")
                else None
            ),
            duration_ms=duration_ms,
            cost_usd=float(state.get("total_cost_usd", 0.0) or 0.0),
        )

    report_raw = state.get("draft_report") or "{}"
    try:
        report = _json.loads(report_raw) if isinstance(report_raw, str) else dict(report_raw)
    except Exception:
        report = {"raw": str(report_raw)[:4000]}
    if not isinstance(report, dict):
        report = {"raw": str(report)[:4000]}

    # (citation guard: criterion #17 defense-in-depth)
    report["citations"] = filter_citations(report.get("citations", {}))

    # (allow-list rewrite: criterion #16 recommend-only)
    try:
        report = allowlist_enforce(report)
    except RecommendOnlyViolation as exc:
        # Should never fire in rewrite mode; if it does (mode=reject), surface
        # the structured block payload.
        return AlertResponse(
            alert_id=alert_id,
            severity="BLOCKED",
            report=build_block_response(
                reason_code="recommend_only_violation",
                rail_name="actions_allowlist",
                rule_name=",".join(ev.get("matched_pattern", "") for ev in exc.events),
                input_snippet=_json.dumps(report)[:400],
                extra={"events": exc.events},
            ),
            citations={},
            trace_id=state.get("trace_id"),
            trace_url=(
                f"{settings.langfuse_host}/trace/{state.get('trace_id')}"
                if state.get("trace_id")
                else None
            ),
            duration_ms=duration_ms,
            cost_usd=float(state.get("total_cost_usd", 0.0) or 0.0),
        )

    degraded = bool(state.get("_degraded_mode", False)) or bool(degraded_override_reason)
    degraded_reason = state.get("_degraded_reason") or degraded_override_reason or None
    footer = DEGRADED_FOOTER if degraded else None

    trace_id = state.get("trace_id")
    trace_url = f"{settings.langfuse_host}/trace/{trace_id}" if trace_id else None

    return AlertResponse(
        alert_id=alert_id,
        severity=state.get("severity", "UNKNOWN"),
        report=report,
        citations=report.get("citations") or state.get("citations") or {},
        trace_id=trace_id,
        trace_url=trace_url,
        duration_ms=duration_ms,
        cost_usd=float(state.get("total_cost_usd", 0.0) or 0.0),
        degraded_mode=degraded,
        degraded_reason=degraded_reason,
        footer=footer,
    )


